/// الدليل الإرشادي: مراحل رحلة العميل داخل يمن سيلو.
class GuideEntry {
  const GuideEntry({
    required this.id,
    required this.stage,
    required this.question,
    required this.answer,
    required this.steps,
    this.tags = const <String>[],
    this.fromAi = false,
  });

  final String id;
  final String stage;
  final String question;
  final String answer;
  final List<String> steps;
  final List<String> tags;
  final bool fromAi;

  factory GuideEntry.fromMap(String id, Map<String, dynamic> m) => GuideEntry(
        id: id,
        stage: (m['stage'] ?? '') as String,
        question: (m['question'] ?? '') as String,
        answer: (m['answer'] ?? '') as String,
        steps: ((m['steps'] as List?) ?? const []).map((e) => '$e').toList(),
        tags: ((m['tags'] as List?) ?? const []).map((e) => '$e').toList(),
        fromAi: (m['fromAi'] as bool?) ?? false,
      );

  Map<String, dynamic> toMap() => {
        'stage': stage,
        'question': question,
        'answer': answer,
        'steps': steps,
        'tags': tags,
        'fromAi': fromAi,
        'approved': true,
      };

  /// كل الكلمات التي يُبحث بها عن هذا السؤال.
  List<String> get keywords => <String>[
        ...question.split(RegExp(r'\s+')),
        ...tags,
      ].where((w) => w.trim().length > 1).toList();
}

